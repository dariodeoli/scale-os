import React, {createRef} from 'react';
import assert from 'node:assert/strict';
import {act, create} from 'react-test-renderer';
import {InputBase, TextareaBase} from '../app/ui/input';
import {Field,FormField} from '../app/ui/field';
import {TextField} from '../app/text-field';
import {EmailField} from '../app/email-field';
import {PasswordField} from '../app/password-field';

import {PHONE_COUNTRIES, phoneValid, emailValid} from '../app/field-rules';
Object.assign(globalThis, {React});
require.extensions['.css']=()=>{};
const {PhoneField}=require('../app/phone-field') as typeof import('../app/phone-field');
const {OptionsSelect}=require('../app/ui/options-select') as typeof import('../app/ui/options-select');

const inputNode = {focus() {focused++;}};
let focused = 0;
const ref = createRef<HTMLInputElement>();
let nativeEvent: unknown;
const native = create(<InputBase ref={ref} name="person" aria-describedby="external" describedBy="help" invalid onChange={event => {nativeEvent = event;}}/>, {createNodeMock: () => inputNode});
assert.equal(ref.current, inputNode);
ref.current!.focus(); assert.equal(focused, 1);
const event = {target: {value: 'á partial '}};
native.root.findByType('input').props.onChange(event);
assert.equal(nativeEvent, event, 'native event identity survives the base');
assert.equal(native.root.findByType('input').props['aria-describedby'], 'external help');
assert.equal(native.root.findByType('input').props['aria-invalid'], true);
const areaRef = createRef<HTMLTextAreaElement>();
const area = create(<TextareaBase ref={areaRef} pending rows={4} defaultValue="partial"/>, {createNodeMock: () => inputNode});
assert.equal(areaRef.current, inputNode);
assert.equal(area.root.findByType('textarea').props.disabled, true);
assert.equal(area.root.findByType('textarea').props.rows, 4);

const field = create(<Field label="Nombre" help="Ayuda" error="Revisá el nombre">{props => <TextField {...props} value="" onChange={() => {}}/>}</Field>);
const fieldInput = field.root.findByType('input');
assert.equal(field.root.findByType('label').props.htmlFor, fieldInput.props.id);
assert.equal(fieldInput.props['aria-describedby'], `${fieldInput.props.id}-help ${fieldInput.props.id}-error`);
assert.equal(fieldInput.props['aria-invalid'], true);
assert.equal(field.root.findByProps({role: 'alert'}).children[0], 'Revisá el nombre');
let changed = '';
const text = create(<TextField value="partial " maxLength={400} onChange={value => {changed = value;}}/>);
text.root.findByType('input').props.onChange({target: {value: ' partial '}});
assert.equal(changed, ' partial ', 'text adapter does not trim input while typing');
assert.equal(text.root.findByType('input').props.maxLength, 400);
const emails = create(<><EmailField value="a@g" onChange={() => {}}/><EmailField value="b@g" onChange={() => {}}/></>);
const emailInputs = emails.root.findAllByType('input');
assert.notEqual(emailInputs[0].props.list, emailInputs[1].props.list);
assert.equal(emailInputs[0].props.maxLength, 254);
assert.equal(emails.root.findAllByType('datalist')[0].props.id, emailInputs[0].props.list);
const emailRef = createRef<HTMLInputElement>();
const pendingEmail = create(<EmailField ref={emailRef} pending value="a@" onChange={value => {changed = value;}}/>, {createNodeMock: () => inputNode});
changed = 'pending';
pendingEmail.root.findByType('input').props.onChange({target: {value: 'a@g'}});
assert.equal(changed, 'pending');
assert.equal(emailRef.current, inputNode);
assert.equal(pendingEmail.root.findByType('input').props.disabled, true);
assert.equal(emailValid(`${'a'.repeat(248)}@x.com`), true);
assert.equal(emailValid(`${'a'.repeat(249)}@x.com`), false);

const passwordRef = createRef<HTMLInputElement>();
const password = create(<PasswordField ref={passwordRef} label="Contraseña" name="password" autoComplete="current-password" value="old" onChange={value => {changed = value;}}/>, {createNodeMock: element => element.type === 'input' ? inputNode : null});
assert.equal(password.root.findByType('input').props.minLength, undefined, 'login gets no new minimum policy');
act(() => password.root.findByType('button').props.onClick());
assert.equal(password.root.findByType('input').props.type, 'text');
assert.equal(password.root.findByType('input').props.value, 'old');
assert.equal(passwordRef.current, inputNode);
act(() => password.update(<PasswordField ref={passwordRef} pending label="Contraseña" name="password" autoComplete="current-password" value="old" onChange={value => {changed = value;}}/>));
changed = 'unchanged';
password.root.findByType('input').props.onChange({target: {value: 'new'}});
act(() => password.root.findByType('button').props.onClick());
assert.equal(changed, 'unchanged');
assert.equal(password.root.findByType('button').props.disabled, true);
assert.equal(password.root.findByType('input').props['aria-busy'], true);

assert.deepEqual(new Set(PHONE_COUNTRIES.map(country => country.code)), new Set(['+595', '+598', '+54', '+55', '+56', '+57', '+51', '+52', '+591', '+1', '+34', '+351']));
for (const country of PHONE_COUNTRIES) {
 const min = country.code === '+595' ? 8 : 6;
 const max = country.code === '+595' ? 9 : 12;
 assert.equal(phoneValid(`${country.code} ${'1'.repeat(min)}`), true);
 assert.equal(phoneValid(`${country.code} ${'1'.repeat(max)}`), true);
 assert.equal(phoneValid(`${country.code} ${'1'.repeat(min - 1)}`), false);
 assert.equal(phoneValid(`${country.code} ${'1'.repeat(max + 1)}`), false);
}
assert.equal(phoneValid('+49 30123456'), false);
const phoneRef = createRef<HTMLInputElement>();
const phone = create(<PhoneField ref={phoneRef} value="+49 30 123456" onChange={value => {changed = value;}}/>, {createNodeMock: element => element.type === 'input' ? inputNode : null});
assert.equal(phoneRef.current, inputNode);
assert.equal(phone.root.findByType(OptionsSelect).props.value, '');
assert.equal(phone.root.findByType('input').props.value, '+49 30 123456');
phone.root.findByType('input').props.onChange({target: {value: '+49 30 1234567'}});
assert.equal(changed, '+49 30 1234567', 'unknown codes round-trip without a country substitution');
act(() => phone.update(<PhoneField value="+" onChange={value => {changed = value;}}/>));
assert.equal(phone.root.findByType('input').props.value, '+');
phone.root.findByType('input').props.onChange({target: {value: '+5'}});
assert.equal(changed, '+5');
act(() => phone.update(<PhoneField value="" onChange={value => {changed = value;}}/>));
act(() => phone.root.findByType(OptionsSelect).props.onChange('+351'));
phone.root.findByType('input').props.onChange({target: {value: '123456'}});
assert.equal(changed, '+351 123456');
act(() => phone.update(<PhoneField value="+351 123456" onChange={value => {changed = value;}}/>));
act(() => phone.root.findByType('input').props.onChange({target: {value: ''}}));
assert.equal(changed, '');
act(() => phone.update(<PhoneField value="" onChange={value => {changed = value;}}/>));
assert.equal(phone.root.findByType(OptionsSelect).props.value, '+351', 'clearing the number retains the chosen country');
act(() => phone.update(<PhoneField value="+351 123456" pending onChange={value => {changed = value;}}/>));
changed = 'blocked';
phone.root.findByType('input').props.onChange({target: {value: '1234567'}});
phone.root.findByType(OptionsSelect).props.onChange('+595');
assert.equal(changed, 'blocked');
assert.equal(phone.root.findByType('input').props.disabled, true);
assert.equal(phone.root.findByType(OptionsSelect).props.disabled, true);
console.log('PASS: native field refs/events, accessible messages, semantic adapters, pending and API phone boundaries');

