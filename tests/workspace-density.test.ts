import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=(name:string)=>readFileSync('app/'+name,'utf8');
const workspace=read('scale-workspace.tsx'),toolbar=read('demo-toolbar.tsx'),personContainer=read('person-container.css');
assert.equal((workspace.match(/<DemoToolbar/g)||[]).length,1);
assert(workspace.indexOf('topbar-workspace-context')<workspace.indexOf('<DemoToolbar'),'the demo toolbar lives in the topbar workspace context');
assert(!toolbar.includes('demo-session-note'));
assert(toolbar.includes('aria-label="Información de la demo"'));
assert(toolbar.includes('Sin dinero real'));
assert(toolbar.includes('disabled={busy}'));
assert(workspace.includes('grid-cols-[minmax(0,1fr)]'),'the sidebar footer keeps one bounded column');
assert(personContainer.includes('overflow:hidden;text-overflow:ellipsis;white-space:nowrap'));
assert(workspace.includes('aria-label="Abrir mi perfil" onClick={()=>setMyProfile(true)}'));
assert(workspace.includes('label="Cerrar sesión" title="Cerrar sesión" size="compact" onClick={logout}'));
const fields=read('operations.tsx'),css=read('operations.css');
assert(fields.includes('columns = true'));
// Additional wide fields are intentional; do not couple this contract to array order.
const wideFields=fields.match(/\[([^\]]+)\]\.includes\(f\.key\)/)?.[1];
assert(wideFields,'Editor must identify fields that span the form');
const wideKeys=new Set(Array.from(wideFields.matchAll(/['"]([^'"]+)['"]/g),match=>match[1]));
for(const key of ['description','drive_links','address','notes'])assert(wideKeys.has(key),`${key} must remain full width`);
const wideExpression=fields.match(/const wide=([^;]+);/)?.[1];
assert(wideExpression);
const isWide=new Function('f',`return ${wideExpression};`) as (field:Record<string,unknown>)=>boolean;
for(const type of ['textarea','url'])assert.equal(isWide({key:'custom',type}),true,`${type} fields remain full width`);
assert.equal(isWide({key:'custom',wide:true}),true,'explicit wide overrides remain available');
for(const key of ['title','legal_name'])assert.equal(isWide({key,type:'text'}),false,`${key} uses compact field-aware sizing`);
assert(fields.includes('f.span??(wide?12:'),'explicit spans override compact defaults');
assert(css.includes('repeat(auto-fit,minmax(min(100%,180px),1fr))'));
assert(css.includes('.ops-form-grid>.dialog-actions'));
assert(css.includes('@media (max-width:540px)'));
console.log('PASS: one compact demo toolbar, separate profile/logout, bounded sidebar footer and responsive form columns (visual QA separate)');
