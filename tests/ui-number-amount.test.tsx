import React, {createRef} from 'react';
import assert from 'node:assert/strict';
import {act, create} from 'react-test-renderer';
import {AmountInput} from '../app/ui/amount';
import {NumberInput, PercentageInput, numberInputValid} from '../app/ui/number';
Object.assign(globalThis, {React});

const changes: string[] = [];
const inputRef = createRef<HTMLInputElement>();
let focused = false;
const carets: number[] = [];
let selection = 0;
const node = {value: '1.234,50', focus() {focused = true;}, setSelectionRange(start: number) {carets.push(start);}, get selectionStart() {return selection;}, set selectionStart(value: number) {selection = value; carets.push(value);}, selectionEnd: 0};
Object.assign(globalThis, {document: {activeElement: node}});
const amount = create(<AmountInput ref={inputRef} id="amount" name="amount" className="w-44" value="1234.50" currency="USD" invalid describedBy="error" required onChange={(value:string) => changes.push(value)}/>, {createNodeMock: element => element.type === 'input' ? node : null});
const input = () => amount.root.findByType('input');
assert.equal(inputRef.current, node, 'ref reaches the renderer input');
inputRef.current!.focus(); assert.equal(focused, true);
assert.equal(input().props.value, '1.234,50');
assert.equal(input().props.inputMode, 'decimal');
assert.equal(input().props.name, 'amount');
assert.equal(input().props.required, true);
assert.equal(input().props['aria-invalid'], true);
assert.equal(input().props['aria-describedby'], 'error');
act(() => input().props.onChange({currentTarget: {value: '1,234.50', selectionStart: 8}}));
assert.equal(changes.at(-1), '1234.50');

act(() => amount.update(<AmountInput ref={inputRef} value="1234" currency="PYG" onChange={(value:string) => changes.push(value)}/>));
assert.equal(input().props.value, '1.234');
assert.equal(input().props.inputMode, 'numeric');
act(() => input().props.onChange({currentTarget: {value: '1.234,50', selectionStart: 8}}));
assert.equal(changes.at(-1), '1234');
act(() => amount.update(<AmountInput value="100.25" currency="USD" pending onChange={(value:string) => changes.push(value)}/>));
assert.equal(input().props.disabled, true);
const count = changes.length;
act(() => input().props.onChange({currentTarget: {value: '100,50', selectionStart: 6}}));
assert.equal(changes.length, count);
act(() => amount.update(<AmountInput value="100.25" currency="USD" integerOnly onChange={() => {}}/>));
assert.equal(input().props.inputMode, 'numeric');
function CaretExample() {
 const [value, setValue] = React.useState('1234.50');
 return <AmountInput value={value} currency="USD" onChange={setValue}/>;
}
const caretExample = create(<CaretExample/>, {createNodeMock: element => element.type === 'input' ? node : null});
// Model the host value after React commits formatting, before its layout effect restores selection.
node.value = '1.234,56';
node.selectionStart = 8;
carets.length = 0;
act(() => caretExample.root.findByType('input').props.onChange({currentTarget: {value: '1,234.56', selectionStart: 8}}));
assert.equal(caretExample.root.findByType('input').props.value, '1.234,56');
assert.deepEqual(carets, [8], 'renderer restores the caret after a controlled value update');

assert.equal(numberInputValid('-1', 'integer'), true);
assert.equal(numberInputValid('0', 'integer'), true);
assert.equal(numberInputValid('', 'decimal'), true);
assert.equal(numberInputValid('', 'decimal', {required: true}), false);
assert.equal(numberInputValid('1.5', 'integer'), false);
assert.equal(numberInputValid('100.01', 'decimal', {max: '100'}), false);
assert.equal(numberInputValid('0.125', 'decimal', {min: '0', max: '1', precision: 3}), true);
assert.equal(numberInputValid('0.125', 'decimal', {precision: 2}), false);
assert.equal(numberInputValid('9007199254740993.01', 'decimal', {max: '9007199254740993.00'}), false, 'range comparisons stay exact above safe integers');
assert.equal(numberInputValid('-9007199254740993.01', 'decimal', {min: '-9007199254740993.00'}), false);
const numberRef = createRef<HTMLInputElement>();
const number = create(<NumberInput ref={numberRef} policy="decimal" value="-" onChange={(value:string) => changes.push(value)}/>, {createNodeMock: () => node});
assert.equal(numberRef.current, node);
assert.equal(number.root.findByType('input').props.value, '-');
number.root.findByType('input').props.onChange({target: {value: '-.'}});
assert.equal(changes.at(-1), '-.', 'partial values are not normalized or discarded');
assert.equal(number.root.findByType('input').props['aria-invalid'], true);
const percent = create(<PercentageInput policy="integer-percent" min="0" max="100" value="101" onChange={(value:string) => changes.push(value)}/>);
assert.equal(percent.root.findByType('input').props['aria-invalid'], true);
act(() => percent.update(<PercentageInput policy="decimal-percent" value="12.5" onChange={(value:string) => changes.push(value)}/>));
assert.equal(percent.root.findByType('input').props.value, '12.5');
assert.equal(percent.root.findByType('input').props['aria-invalid'], undefined);
act(() => percent.update(<PercentageInput policy="ratio" min="0" max="1" value="0.125" onChange={(value:string) => changes.push(value)}/>));
assert.equal(percent.root.findByType('input').props.value, '0.125', 'ratio retains its own unit');
percent.root.findByType('input').props.onChange({target: {value: '0.'}});
assert.equal(changes.at(-1), '0.');
act(() => percent.update(<PercentageInput policy="ratio" value="2" onChange={() => {}}/>));
assert.equal(percent.root.findByType('input').props['aria-invalid'], undefined, 'a range must be explicit');
console.log('PASS: real MoneyInput currency/ref/pending bridge and exact explicit numeric policies without value conversion');
