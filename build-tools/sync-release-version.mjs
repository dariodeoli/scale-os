import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const check=process.argv.includes('--check');
const release=JSON.parse(readFileSync(new URL('../release/version.json',import.meta.url),'utf8'));
if(!/^\d+\.\d+\.\d+$/.test(release.version))throw new Error('release/version.json debe contener una versión semántica, por ejemplo 1.0.33.');
const update=(relative,next)=>{
 const path=fileURLToPath(new URL(relative,import.meta.url)),current=readFileSync(path,'utf8');
 if(current===next)return false;
 if(check)throw new Error(`${relative} no coincide con release/version.json. Ejecutá npm run release:sync.`);
 writeFileSync(path,next);return true;
};
const packagePath=fileURLToPath(new URL('../package.json',import.meta.url)),packageJson=JSON.parse(readFileSync(packagePath,'utf8'));
packageJson.version=release.version;
const lockPath=fileURLToPath(new URL('../package-lock.json',import.meta.url)),lock=JSON.parse(readFileSync(lockPath,'utf8'));
lock.version=release.version;lock.packages[''].version=release.version;
// El API vive en backend/ del mismo repositorio: una sola fuente de versión
// mantiene alineados el servicio web y el servicio API de Coolify.
const backendPackagePath=fileURLToPath(new URL('../backend/package.json',import.meta.url)),backendPackage=JSON.parse(readFileSync(backendPackagePath,'utf8'));
backendPackage.version=release.version;
const backendLockPath=fileURLToPath(new URL('../backend/package-lock.json',import.meta.url)),backendLock=JSON.parse(readFileSync(backendLockPath,'utf8'));
backendLock.version=release.version;backendLock.packages[''].version=release.version;
const backendRelease=JSON.parse(readFileSync(new URL('../backend/release-version.json',import.meta.url),'utf8'));
backendRelease.version=release.version;
const changed=[
 update('../app/app-version.ts',`// Generated from release/version.json. Do not edit this file directly.\nexport const APP_VERSION = '${release.version}';\n`),
 update('../package.json',`${JSON.stringify(packageJson,null,2)}\n`),
 update('../package-lock.json',`${JSON.stringify(lock,null,2)}\n`),
 update('../backend/package.json',`${JSON.stringify(backendPackage,null,2)}\n`),
 update('../backend/package-lock.json',`${JSON.stringify(backendLock,null,2)}\n`),
 update('../backend/release-version.json',`${JSON.stringify(backendRelease,null,2)}\n`),
].some(Boolean);
console.log(changed?`Synced Scale OS release v${release.version} (web + backend).`:`Scale OS release v${release.version} is synchronized (web + backend).`);
